#!/usr/bin/env python3
"""Generates RealDatasetCorpus.kt from the cleaned/relabeled JSONL files produced by the other
scripts in this directory. Regenerate by re-running the full pipeline (fetch -> process/triage
-> generate) rather than hand-editing the .kt file.

Each source's rows are split into chunked private functions (not one big listOf(...) literal)
because Kotlin/JVM's 64KB-per-method bytecode limit was hit with ~3000 entries in a single
object initializer -- MethodTooLargeException on RealDatasetCorpus.<clinit>. Splitting into a
function per chunk moves each chunk's listOf(...) into its OWN method body instead of the
object's shared static initializer, which is what was overflowing.
"""
import json
from collections import Counter

CHUNK_SIZE = 150


def kt_string(s: str) -> str:
    return json.dumps(s)[1:-1].replace("$", "\\$")


def load(path):
    return [json.loads(l) for l in open(path)]


def chunked(items, size=CHUNK_SIZE):
    for i in range(0, len(items), size):
        yield items[i : i + size]


def emit_source(lines, fn_prefix, rows, ti_base, comment):
    """rows: list of (sourceapp_expr, sender_expr, text, expected_expr) tuples."""
    lines.append(f"    // {comment}")
    chunk_fn_names = []
    for c, chunk in enumerate(chunked(rows)):
        fn_name = f"{fn_prefix}_{c}"
        chunk_fn_names.append(fn_name)
        lines.append(f"    private fun {fn_name}(): List<RCase> = listOf(")
        for i, (sourceapp, sender, text, expected) in enumerate(chunk):
            ti = ti_base + c * CHUNK_SIZE + i
            lines.append(f"        RCase({sourceapp}, {sender}, \"{kt_string(text)}\", {expected}, {ti}, 0, false),")
        lines.append("    )")
    lines.append(f"    private fun {fn_prefix}(): List<RCase> = " + " + ".join(f"{n}()" for n in chunk_fn_names))
    lines.append("")


def main():
    sms_spam = [r["text"] for r in load("tools/dataset_cache/raw/sms_spam_clean.jsonl")]
    sa_subjects = [r["text"] for r in load("tools/dataset_cache/raw/spamassassin_subjects.jsonl")]
    sms_ham = load("tools/dataset_cache/raw/sms_ham_final.jsonl")
    enron = load("tools/dataset_cache/raw/enron_final.jsonl")
    sgd = load("tools/dataset_cache/raw/sgd_sampled.jsonl")

    lines = []
    lines.append("package com.futurepath.actionbox.classification")
    lines.append("")
    lines.append("private typealias RCase = SyntheticNotificationCorpus.Case")
    lines.append("")
    lines.append("/**")
    lines.append(" * Real (not synthetic, not template-generated) text from public datasets, mapped to")
    lines.append(" * ActionBox's 6 categories. Generated by tools/dataset_integration/generate_kotlin_corpus.py")
    lines.append(" * from the cleaned/relabeled JSONL files that script's sibling scripts produce -- see")
    lines.append(" * tools/dataset_integration/ for the fetch/triage/relabel pipeline for each source, and the")
    lines.append(" * session report for the full per-source extraction/relabeling/quality-issue writeup.")
    lines.append(" *")
    lines.append(" * Sources actually used (see the session report for the ones evaluated and excluded, and why):")
    lines.append(f" *  - SMS Spam Collection (UCI, spam rows -> NOISE directly): {len(sms_spam)} examples")
    lines.append(f" *  - SMS Spam Collection (ham rows, heuristically triaged + manually spot-checked across")
    lines.append(f" *    the other 5 categories): {len(sms_ham)} examples")
    lines.append(f" *  - SpamAssassin Public Corpus (spam subject lines only, not full bodies -> NOISE): {len(sa_subjects)} examples")
    lines.append(f" *  - Enron Email Corpus (subject+opening-sentence sample, heuristically triaged + manually")
    lines.append(f" *    spot-checked): {len(enron)} examples")
    lines.append(f" *  - Schema-Guided Dialogue (CC BY-SA 4.0; SYSTEM-turn CONFIRM/REQUEST -> ACTION,")
    lines.append(f" *    NOTIFY_SUCCESS -> FYI; USER turns excluded as wrong-direction): {len(sgd)} examples")
    lines.append(" *")
    lines.append(" * Ling-Spam was researched but no license-safe direct-download mirror could be located this")
    lines.append(" * session (skipped rather than guessed at a URL). Banking77/HWU64/MASSIVE were inspected as")
    lines.append(" * vocabulary/phrasing donors per the task, contributed zero corpus rows (see the session")
    lines.append(" * report), and are not represented here. DailyDialog/TREC 2007/Reddit/EPA/the Kaggle")
    lines.append(" * email-intent set were excluded per the task's license/access guidance and never fetched.")
    lines.append(" */")
    lines.append("object RealDatasetCorpus {")
    lines.append("")
    lines.append("    private const val SMS = \"com.google.android.apps.messaging\"")
    lines.append("    private const val GMAIL = \"com.google.android.gm\"")
    lines.append("")

    emit_source(
        lines, "smsSpam",
        [("SMS", "\"Unknown\"", t, "ClassifiedState.NOISE") for t in sms_spam],
        30000, "SMS Spam Collection (UCI), spam rows -- direct NOISE mapping, no relabeling needed."
    )
    emit_source(
        lines, "spamassassinSubjects",
        [("GMAIL", "\"Unknown\"", t, "ClassifiedState.NOISE") for t in sa_subjects],
        31000, "SpamAssassin Public Corpus, spam subject lines only (not full bodies, which read "
               "nothing like a push-notification's text) -- direct NOISE mapping."
    )
    emit_source(
        lines, "enron",
        [("GMAIL", "\"Coworker\"", r["text"], f"ClassifiedState.{r['label']}") for r in enron],
        32000, "Enron Email Corpus sample (subject+opening-sentence), heuristically triaged then "
               "manually spot-checked -- see tools/dataset_integration/triage_enron.py."
    )
    emit_source(
        lines, "smsHam",
        [("SMS", "\"Friend\"", r["text"], f"ClassifiedState.{r['label']}") for r in sms_ham],
        33000, "SMS Spam Collection ham rows, heuristically triaged then manually spot-checked -- "
               "see tools/dataset_integration/triage_sms_ham.py. Real peer-to-peer texting "
               "register, the closest of all sources used here to ActionBox's actual target domain."
    )
    emit_source(
        lines, "sgd",
        [("GMAIL", "\"Service\"", r["text"], f"ClassifiedState.{r['label']}") for r in sgd],
        34000, "Schema-Guided Dialogue (CC BY-SA 4.0), SYSTEM-turn utterances for specific dialogue "
               "acts -- see tools/dataset_integration/extract_sgd.py. Crowdsourced/paraphrased, not "
               "organically-occurring text, but real human-written language (not template-generated)."
    )

    lines.append("    fun buildCorpus(): List<RCase> =")
    lines.append("        smsSpam() + spamassassinSubjects() + enron() + smsHam() + sgd()")
    lines.append("}")

    with open("app/src/test/java/com/futurepath/actionbox/classification/RealDatasetCorpus.kt", "w") as f:
        f.write("\n".join(lines) + "\n")

    total = len(sms_spam) + len(sa_subjects) + len(enron) + len(sms_ham) + len(sgd)
    print(f"Wrote RealDatasetCorpus.kt with {total} examples")
    by_label = Counter()
    for t in sms_spam + sa_subjects:
        by_label["NOISE"] += 1
    for row in enron + sms_ham + sgd:
        by_label[row["label"]] += 1
    print(by_label)


if __name__ == "__main__":
    main()
